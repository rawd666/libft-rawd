#include "libft.h"

void	ft_putnbr_fd(int n, int fd)
{
	char	c;

	if (n < 0)
	{
		n *= -1;
		write(1, "-", 1);
	}
	c = n % 10 + '0';
	if (n > 10)
		ft_putnbr_fd(n / 10, fd);
	write(fd, &c, 1);
}

